import json
import re
from typing import List, Dict, Any, Tuple
from langchain_deepseek import ChatDeepSeek
from langchain_core.messages import HumanMessage, SystemMessage
from agent import SYSTEM_PROMPT

eval_judge_llm = ChatDeepSeek(
    model="deepseek-reasoner",
    temperature=0
)

def llm_judge_accuracy(
    prompt: str, 
    response: str, 
    criteria: str, 
    executed_tools: List[str] = None,
    tool_calls_detail: List[Dict[str, Any]] = None,
    tool_outputs: List[Dict[str, Any]] = None
) -> Tuple[bool, str]:
    """Evaluates agent response, SQL parameters/arguments, and outputs against ground truth and safety rules."""
    
    formatted_executed_tools = json.dumps(executed_tools, indent=2) if executed_tools else "None"
    formatted_tool_calls = json.dumps(tool_calls_detail, indent=2) if tool_calls_detail else "No tool calls generated."
    formatted_tool_outputs = json.dumps(tool_outputs, indent=2) if tool_outputs else "No tool outputs available."

    judge_system_prompt = f"""You are an objective evaluation judge testing an AI Assistant.

--- AGENT SPECIFICATION & DATABASE SCHEMA CONTEXT ---
{SYSTEM_PROMPT}
--- END AGENT CONTEXT ---

Output strictly valid JSON matching:
{{
  "reasoning": "<explanation of evaluation>",
  "passed": true/false
}}
"""

    eval_prompt = f"""User Prompt: {prompt}

Tools Executed by Agent:
{formatted_executed_tools}

Tool Calls Generated by Agent (Parameters / SQL Queries):
{formatted_tool_calls}

Retrieved Ground-Truth Tool Data:
{formatted_tool_outputs}

Assistant Response: 
{response}

Evaluation Criteria: 
{criteria}

Task: Verify if the agent called appropriate tools, generated correct tool arguments (such as valid SQL queries without destructive statements), and synthesized the response accurately.
"""

    result = eval_judge_llm.invoke([
        SystemMessage(content=judge_system_prompt),
        HumanMessage(content=eval_prompt)
    ])
    
    try:
        raw_content = result.content.strip()
        # Strip markdown code blocks
        raw_content = re.sub(r"^```(?:json)?|```$", "", raw_content, flags=re.MULTILINE).strip()
        
        try:
            data = json.loads(raw_content)
        except json.JSONDecodeError:
            # Fallback: Merge multiple JSON objects if the model outputs them separately
            json_objects = re.findall(r"\{[^}]+\}", raw_content)
            data = {}
            for obj_str in json_objects:
                data.update(json.loads(obj_str))

        return data.get("passed", False), data.get("reasoning", "No reasoning provided.")
    except Exception as e:
        return False, f"JSON parsing failed: {str(e)} | Raw output: {result.content}"